// URDF (ROS 2) export generated from the same assembly / robot model used by the simulator.

import { getItem } from './catalog';
import { urdfGeometry } from './geometry';
import { computeFrames, findInst, type Assembly } from './assembly';
import type { RobotModel } from './robotModel';
import { eulerDeg, rpyFromR, tf, tinv, tmul, type Tf, type M3 } from './math';

const f = (v: number) => (Math.abs(v) < 1e-12 ? '0' : v.toPrecision(6).replace(/\.?0+$/, ''));
const xyz = (p: number[]) => p.map(f).join(' ');
const rpy = (R: M3) => rpyFromR(R).map(f).join(' ');
const safe = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_');

function visuals(a: Assembly, uids: string[], bodyFrame: Tf, frames: ReturnType<typeof computeFrames>, which: (uid: string) => 'housing' | 'output' | 'all'): string {
  let out = '';
  for (const uid of uids) {
    const inst = findInst(a, uid);
    if (!inst) continue;
    const item = getItem(inst.item);
    const T = frames.get(uid)?.T;
    if (!T) continue;
    const w = which(uid);
    item.shapes.forEach((sh, k) => {
      if (w === 'housing' && sh.onOutput) return;
      if (w === 'output' && !sh.onOutput) return;
      const S = tmul(tinv(bodyFrame), tmul(T, tf(eulerDeg(sh.rot), sh.pos)));
      const geom = urdfGeometry(sh);
      const block = `      <origin xyz="${xyz(S.p)}" rpy="${rpy(S.R)}"/>\n      <geometry>${geom}</geometry>\n`;
      out += `    <visual name="${safe(uid)}_${k}">\n${block}      <material name="${safe(item.category)}"/>\n    </visual>\n`;
      out += `    <collision name="${safe(uid)}_${k}">\n${block}    </collision>\n`;
    });
  }
  return out;
}

const inertial = (m: number, c: number[], I: number[]) =>
  `    <inertial>\n      <origin xyz="${xyz(c)}" rpy="0 0 0"/>\n      <mass value="${f(m)}"/>\n      <inertia ixx="${f(I[0])}" ixy="${f(I[1])}" ixz="${f(I[2])}" iyy="${f(I[4])}" iyz="${f(I[5])}" izz="${f(I[8])}"/>\n    </inertial>\n`;

export function exportURDF(a: Assembly, model: RobotModel): string {
  const frames = computeFrames(a, {});
  const name = safe(a.name || 'roboverse_robot');
  const gbSet = new Map(model.joints.map((J, i) => [J.gbUid, i]));
  // a gearbox's housing shapes belong to the body that carries it, its output shapes to the next body
  const housingOrAll = (uid: string) => (gbSet.has(uid) ? 'housing' : 'all') as 'housing' | 'all';
  let s = `<?xml version="1.0"?>\n<!-- Generated by ROBOVERSE from assembly “${a.name}”.\n     Geometry: ROBOVERSE procedural reference parts (CC BY 4.0). Units: SI (m, kg, rad).\n     Mass properties computed from part geometry and catalog masses. -->\n<robot name="${name}">\n`;
  for (const mat of ['Structure', 'Actuators', 'Transmissions', 'Links', 'End-effectors', 'Sensors', 'Electronics'])
    s += `  <material name="${mat}"><color rgba="${mat === 'Links' ? '0.9 0.5 0.2 1' : mat === 'Actuators' ? '0.2 0.22 0.26 1' : '0.7 0.72 0.76 1'}"/></material>\n`;
  s += `  <link name="world"/>\n  <joint name="world_fixed" type="fixed">\n    <parent link="world"/>\n    <child link="base_link"/>\n  </joint>\n`;
  s += `  <link name="base_link">\n${inertial(model.base.m, model.base.c, model.base.I)}${visuals(a, model.base.uids, tf(), frames, housingOrAll)}  </link>\n`;
  model.joints.forEach((J, i) => {
    const ln = `link_${i + 1}`;
    const parent = i === 0 ? 'base_link' : `link_${i}`;
    const gbOut = visuals(a, [J.gbUid], J.F0, frames, () => 'output');
    s += `  <link name="${ln}">\n${inertial(J.body.m, J.body.c, J.body.I)}${gbOut}${visuals(a, J.bodyUids, J.F0, frames, housingOrAll)}  </link>\n`;
    s += `  <joint name="joint_${i + 1}" type="${J.type}">\n    <parent link="${parent}"/>\n    <child link="${ln}"/>\n    <origin xyz="${xyz(J.X.p)}" rpy="${rpy(J.X.R)}"/>\n    <axis xyz="0 0 1"/>\n    <limit lower="${f(J.lo)}" upper="${f(J.hi)}" effort="${f(J.gear.T_peak)}" velocity="${f(J.vmax)}"/>\n    <dynamics damping="${f(J.viscous)}" friction="${f(J.coulomb)}"/>\n  </joint>\n`;
  });
  s += `  <link name="tool0"/>\n  <joint name="tool0_fixed" type="fixed">\n    <parent link="${model.n ? `link_${model.n}` : 'base_link'}"/>\n    <child link="tool0"/>\n    <origin xyz="${xyz(model.tool.p)}" rpy="${rpy(model.tool.R)}"/>\n  </joint>\n`;
  // transmissions (ROS 1 style, still parsed by ros2_control) and ros2_control block
  model.joints.forEach((J, i) => {
    s += `  <transmission name="trans_${i + 1}">\n    <type>transmission_interface/SimpleTransmission</type>\n    <joint name="joint_${i + 1}"><hardwareInterface>hardware_interface/EffortJointInterface</hardwareInterface></joint>\n    <actuator name="motor_${i + 1}"><mechanicalReduction>${f(J.gear.ratio)}</mechanicalReduction></actuator>\n  </transmission>\n`;
  });
  s += `  <ros2_control name="${name}_system" type="system">\n    <hardware>\n      <plugin>mock_components/GenericSystem</plugin>\n    </hardware>\n`;
  model.joints.forEach((J, i) => {
    s += `    <joint name="joint_${i + 1}">\n      <command_interface name="position"><param name="min">${f(J.lo)}</param><param name="max">${f(J.hi)}</param></command_interface>\n      <command_interface name="effort"><param name="min">${f(-J.gear.T_peak)}</param><param name="max">${f(J.gear.T_peak)}</param></command_interface>\n      <state_interface name="position"><param name="initial_value">0.0</param></state_interface>\n      <state_interface name="velocity"/>\n      <state_interface name="effort"/>\n    </joint>\n`;
  });
  s += `  </ros2_control>\n</robot>\n`;
  return s;
}
